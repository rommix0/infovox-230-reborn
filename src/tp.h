/* class flags of a text char: the table for 0..0x7f, tp_char_class (national charset
 * remap) for 0x80..0xff, as the DLL does at every test */
static inline unsigned short tp_class(Core *c, unsigned char ch)
{
    return (signed char)ch < 0 ? tp_char_class(c, ch) : c->class_flags[ch];
}


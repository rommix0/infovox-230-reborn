/* Frame generation (DLL 0x10019780-0x10019f4f opbatch.c, 0x1001c4f0-0x1001e88f
 * opsmooth.c and opstart.c).
 *
 * op_start_utterance moves the finished segment list to Core.out and sets up one Track
 * per parameter; op_next_frame then produces one frame per call (the synth's frame
 * source). Each track walks the parameter's time points through Core.out: the segment's
 * own item for that parameter, else the phoneme record's default. A point is a word
 * {time:s8, value:u8}; the time is a frame offset from the segment start. The A1 type
 * code of each parameter selects the op_t* handler that turns the points into the
 * output value in Core.outval.
 */

#define OUT_HEAD(c)  ((Seg *)&(c)->out.head)
#define OUT_TAIL(c)  ((Seg *)&(c)->out.tail)

/* op_data.c (generated by tools/gen_op_data.py): the DLL's constant block 0x100489d0..
 * 0x10048ecf. The lookups index it without bounds checks, like the DLL, so the three
 * tables are kept in one array in their original order. */
extern const short op_const[640];
#define OP_COSINE    (op_const + 0)     /* 0x100489d0 [129]: 16384*(1-cos(pi*i/128)) */
#define OP_RATE      (op_const + 132)   /* 0x10048ad8 [65]: 256/(2i), [0] = 256 */
#define OP_VALMAP    (op_const + 200)   /* 0x10048b60 [260]: value remap when A1 == 0x80 */


/* test builds (CW_COVERAGE): which A1 types and branches ran */
enum { OPC_WRAP, OPC_BLOCK_STEP, OPC_NEXT_SKIP, OPC_NEXT_ITEM, OPC_NEXT_DEFAULT, OPC_NEXT_NONE,
       OPC_VOICE_DIRTY, OPC_A0_ADJUST, OPC_MARK_TOGGLE, OP_COV_N };
#define OP_COV_NAMES {"item wrap", "ItemBlk step", "next_seg skip", "next_seg item", \
                      "next_seg default", "next_seg none", "voice_dirty", "voice[0] adjust", \
                      "mark_param toggle"}

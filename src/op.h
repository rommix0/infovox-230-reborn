extern unsigned long op_type_count[33], op_cov[OP_COV_N];
#define OP_COV(k) (op_cov[k]++)
#else
#define OP_COV(k) ((void)0)
#endif

/* helpers shared by opsmooth.c and opstart.c: a point or item header word */
static inline short op_tcode(unsigned short w)        /* time byte, signed */
{
    return (signed char)(w >> 8);
}
static inline short op_npts(unsigned short w)         /* item header: payload words */
{
    return (w >> 1) & 0x7f;
}
/* the DLL's "past the end of this node" step: p0 moves to the next block's data and
 * p1 is set 0x38 bytes further (past the node; only npts bounds the reads) */
static inline void op_track_wrap(Track *t)
{
    OP_COV(OPC_WRAP);
    t->p0 = t->p2;
    t->p1 = (unsigned short *)((char *)t->p2 + 0x38);
}


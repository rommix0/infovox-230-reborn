"""Extract the text side's and ttsctrl.c's constant tables from bin/Ivx230nt.dll into
src/tp_data.c.

0x10048508..0x10048767 holds (tp.h):
  TP_CHARSET1 0x10048508 [128]  8-bit char -> national char when Core.charset bit 0
  TP_CHARSET2 0x10048588 [128]  same for charset bit 1 (the engine uses 2)
  TP_XLAT     0x100485e8        built-in 2-char transliterations, indexed by
                                tp_xlat_char's code: +0x20 (0x10048608) the default
                                table and +0x80 (0x10048668) the Spanish/Italian one for
                                codes < 0x60, the base itself for codes >= 0xe0
  TP_CLASS80  0x100486e8 [128]  class codes of 0x80..0xff for files without H[14]
tp_xlat_char indexes these without bounds checks, so the block is kept as one array.
Then (tts.h):
  tts_param_names  0x10048768  29 pointers to the 2-char parameter names DR..ZZ
  tts_voice_defaults 0x100487e0  voices 0..4, 29 words each, and the 3 words after them:
                                 the voice copies use Core.ntotal words (32 before a bind)
Run from anywhere:  python tools/gen_tp_data.py
"""
import os
import struct
import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
DLL = os.path.join(HERE, '..', 'bin', 'Ivx230nt.dll')
OUT = os.path.join(HERE, '..', 'src', 'tp_data.c')
BASE = 0x10000000
START, END = 0x10048508, 0x10048768
NAMES, NNAMES = 0x10048768, 29
VOICES, NVOICE = 0x100487e0, 5 * 29


def main():
    pe = pefile.PE(DLL)
    b = pe.get_data(START - BASE, END - START)
    assert b[:4] == bytes([0x8e, 0x8f, 0x80, 0x90])          # charset 1: first entries
    assert b[0x100:0x103] == b'"C\x00'                          # 0x10048608 default xlat
    assert b[0x160:0x164] == b'"C:u'                            # 0x10048668 SP/IT xlat
    assert b[0x1e0:0x1e2] == b'\x03\x02'                        # 0x100486e8 class codes
    names = [pe.get_data(p - BASE, 2).decode()
             for p in struct.unpack('<%dI' % NNAMES, pe.get_data(NAMES - BASE, 4 * NNAMES))]
    assert names[0] == 'DR' and names[25] == 'F0'
    v = struct.unpack('<%dh' % (NVOICE + 3), pe.get_data(VOICES - BASE, 2 * (NVOICE + 3)))
    assert v[1:4] == (64, 64, 64) and v[25] == 64
    out = ['/* Generated by tools/gen_tp_data.py from bin/Ivx230nt.dll -- do not edit by hand. */',
           '#include "tts.h"', '',
           '/* 0x%08x..0x%08x: TP_CHARSET1 at [0], TP_CHARSET2 at [0x80], TP_XLAT at [0xe0],'
           % (START, END - 1),
           ' * TP_CLASS80 at [0x1e0] */',
           'const unsigned char tp_const[%d] = {' % len(b)]
    for i in range(0, len(b), 16):
        out.append('    ' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',')
    out += ['};', '',
            '/* 0x%08x: the pointer table of the built-in parameter names */' % NAMES,
            'const char tts_param_names[%d][3] = {' % NNAMES]
    for i in range(0, NNAMES, 10):
        out.append('    ' + ', '.join('"%s"' % n for n in names[i:i + 10]) + ',')
    out += ['};', '',
            '/* 0x%08x: voices 0..4 (29 words each) and the 3 words after them */' % VOICES,
            'const short tts_voice_defaults[%d] = {' % (NVOICE + 3)]
    for i in range(0, NVOICE + 3, 29):
        out.append('    ' + ', '.join('%d' % x for x in v[i:i + 29]) + ',')
    out += ['};', '']
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', OUT)


if __name__ == '__main__':
    main()

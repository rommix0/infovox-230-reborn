"""Extract the synthesizer's constant tables from bin/Ivx230nt.dll into src/synth_data.c.

Doubles are written as C99 hex-float literals so the port uses bit-identical values.
Run from tools/:  python gen_synth_data.py
"""
import os, struct
import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
DLL = os.path.join(HERE, '..', 'bin', 'Ivx230nt.dll')
OUT = os.path.join(HERE, '..', 'src', 'synth_data.c')
BASE = 0x10000000

pe = pefile.PE(DLL)

def rd(va, n):
    return pe.get_data(va - BASE, n)

def hexf(d):
    return float.hex(d).replace('0x', '0x', 1)

def main():
    out = ['/* Generated by tools/gen_synth_data.py from bin/Ivx230nt.dll -- do not edit by hand. */',
           '#include "ivx.h"', '']

    names = [rd(0x10049518 + 4 * i, 4).split(b'\0')[0].decode() for i in range(32)]
    out.append('/* 0x10049518: 2-char parameter codes named by the synth map */')
    out.append('const char synth_param_names[32][4] = {')
    out.append('    ' + ', '.join('"%s"' % n for n in names))
    out.append('};')
    out.append('')

    for va, cname in ((0x10048ed0, 'synth_map_mode0'), (0x10048fd0, 'synth_map_alt')):
        out.append('/* 0x%08x: {name, frame_index, def} (map_sel %s) */' % (va, '0' if cname.endswith('0') else '!= 0'))
        out.append('const SynthMapEntry %s[32] = {' % cname)
        for i in range(32):
            p, idx, dflt = struct.unpack('<ihh', rd(va + 8 * i, 8))
            name = rd(p, 4).split(bytes(1))[0].decode()   # 0x10049518 (mode 0) / 0x10049598 (alt)
            assert name == names[i]
            out.append('    {synth_param_names[%d], %d, %d},' % (i, idx, dflt))
        out.append('};')
        out.append('')

    out.append('/* 0x10048ec8 */')
    out.append('const short synth_default_f06 = %d;' % struct.unpack('<h', rd(0x10048ec8, 2)))
    out.append('')

    bw = struct.unpack('<32h', rd(0x100494d0, 64))
    out.append('/* 0x100494d0: extra bandwidth (Hz) per B index */')
    out.append('const short bw_delta_hz[32] = {')
    for i in range(0, 32, 8):
        out.append('    ' + ', '.join('%d' % v for v in bw[i:i + 8]) + ',')
    out.append('};')
    out.append('')

    fr = struct.unpack('<128d', rd(0x100490d0, 128 * 8))
    out.append('/* 0x100490d0: F_k = 200*2^((k-3)/24) Hz (exact values from the DLL) */')
    out.append('const double freq_index_hz[128] = {')
    for i in range(0, 128, 4):
        out.append('    ' + ', '.join(hexf(v) for v in fr[i:i + 4]) + ',')
    out.append('};')
    out.append('')

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', newline='\n').write('\n'.join(out))
    print('wrote', os.path.normpath(OUT))

main()

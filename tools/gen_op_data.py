"""Extract the frame generator's constant block from bin/Ivx230nt.dll into src/op_data.c.

0x100489d0..0x10048ecf holds the cosine ramp, the approach-rate table and the value remap
table (op.h: OP_COSINE, OP_RATE, OP_VALMAP) followed by unrelated bytes. The DLL indexes
the tables with unchecked parameter values, so the whole block is kept as one array.
Run from anywhere:  python tools/gen_op_data.py
"""
import os, struct
import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
DLL = os.path.join(HERE, '..', 'bin', 'Ivx230nt.dll')
OUT = os.path.join(HERE, '..', 'src', 'op_data.c')
BASE = 0x10000000
START, END = 0x100489d0, 0x10048ed0


def main():
    pe = pefile.PE(DLL)
    words = struct.unpack('<%dh' % ((END - START) // 2), pe.get_data(START - BASE, END - START))
    assert words[0] == 0 and words[128] == 32767            # cosine ramp 0..32767
    assert words[132:135] == (256, 128, 64)                  # 0x10048ad8: rate table
    assert words[200] == 55 and len(words) == 640            # 0x10048b60: value remap
    out = ['/* Generated by tools/gen_op_data.py from bin/Ivx230nt.dll -- do not edit by hand. */',
           '#include "op.h"', '',
           '/* 0x%08x..0x%08x: OP_COSINE at [0], OP_RATE at [132], OP_VALMAP at [200] */' % (START, END - 1),
           'const short op_const[%d] = {' % len(words)]
    for i in range(0, len(words), 12):
        out.append('    ' + ', '.join('%d' % v for v in words[i:i + 12]) + ',')
    out += ['};', '']
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
